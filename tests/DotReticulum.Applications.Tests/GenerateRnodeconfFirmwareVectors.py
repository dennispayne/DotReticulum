"""Execute actual upstream flasher-plan function; capture paths/tools, never run them."""
import ast
import hashlib
import json
import os
from pathlib import Path
import sys
from types import SimpleNamespace
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tests" / "Interop"))
sys.path.insert(0, os.environ["DOTRETICULUM_UPSTREAM"])
from reference_environment import verify_reference
verify_reference(require_lxmf=True)
from RNS.Utilities import rnodeconf as reference

source = Path(reference.__file__)
tree = ast.parse(source.read_text(encoding="utf-8"))
method = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "get_flasher_call")
namespace = dict(vars(reference))
namespace.update(UPD_DIR="{cache}", CNF_DIR="{state}", EXT_DIR="{extracted}",
                 args=SimpleNamespace(port="{port}", baud_flash="{baud}"),
                 sys=SimpleNamespace(executable="{python}"))
exec(compile(ast.Module(body=[method], type_ignores=[]), str(source), "exec"), namespace)
variants = sorted({v[4] for v in reference.models.values() if v[4]} | {"extracted_rnode_firmware.zip"})
plans = {}
with patch("shutil.which", side_effect=lambda p: p), patch("os.path.isfile", return_value=True), patch("os.chmod"):
    for version in ("1.54", "1.55", "1.86"):
        namespace["selected_version"] = version
        for platform in (reference.ROM.PLATFORM_AVR, reference.ROM.PLATFORM_ESP32, reference.ROM.PLATFORM_NRF52):
            for filename in variants:
                with patch.object(reference.RNS, "log"):
                    plan = namespace["get_flasher_call"](platform, filename)
                if plan:
                    # The reference NRF52 branch accepts every filename; keep only its zip models.
                    if platform == reference.ROM.PLATFORM_NRF52 and not filename.endswith(".zip"):
                        continue
                    plans[f"{platform:02x}/{version}/{filename}"] = [p.replace(version, "{version}") for p in plan]

result = {
    "revision": "a29bfb51c468945c96a1ee22cae0114e993e2391",
    "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
    "adapter": "Execute AST-extracted original get_flasher_call; which/file presence/chmod captured; no processes.",
    "models": {f"{k:02x}": v for k, v in reference.models.items()},
    "products": {f"{k:02x}": v for k, v in reference.products.items()},
    "vendor_keys": reference.known_keys,
    "plans": plans,
}
text = json.dumps(result, indent=2) + "\n"
(Path(__file__).parent / "Fixtures" / "rnodeconf-firmware-vectors.json").write_text(text, encoding="utf-8")
code = '// Generated by GenerateRnodeconfFirmwareVectors.py executing the pinned upstream. Do not edit.\n'
code += 'namespace DotReticulum.Applications.Rnodeconf;\n\ninternal static class RnodeconfReferenceData\n{\n'
code += '    internal const string Json = """\n' + text.rstrip() + '\n""";\n}\n'
(ROOT / "src" / "DotReticulum.Applications" / "Rnodeconf" / "RnodeconfReferenceData.cs").write_text(code, encoding="utf-8")
print(f"Verified import {reference.__file__}; generated {len(plans)} source-executed flash plans, {len(reference.models)} models")
